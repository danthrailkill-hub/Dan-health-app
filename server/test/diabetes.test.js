// Run with: npm test   (uses Node's built-in test runner, no extra dependencies)
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { importCsv } from '../src/diabetes/importers.js';
import { computeSummary, findLows, classify } from '../src/diabetes/stats.js';
import { normalizeTs, epochToWallClock } from '../src/diabetes/time.js';

const S = { units: 'mg/dL', target_low: 70, target_high: 180, very_low: 54, very_high: 250 };

test('normalizeTs handles device timestamp formats', () => {
  assert.equal(normalizeTs('2024-03-05T08:07:09'), '2024-03-05T08:07:09');
  assert.equal(normalizeTs('2024-03-05 8:07'), '2024-03-05T08:07:00');
  assert.equal(normalizeTs('03-05-2024 08:07'), '2024-03-05T08:07:00');
  assert.equal(normalizeTs('05/03/2024 08:07', 'DMY'), '2024-03-05T08:07:00');
  assert.equal(normalizeTs('03/05/2024 12:30 AM'), '2024-03-05T00:30:00');
  assert.equal(normalizeTs('03/05/2024 1:30 PM'), '2024-03-05T13:30:00');
  assert.equal(normalizeTs(''), null);
});

test('epochToWallClock converts to the configured timezone', () => {
  assert.equal(epochToWallClock(Date.parse('2024-07-01T12:00:00Z'), 'America/Chicago'), '2024-07-01T07:00:00');
});

